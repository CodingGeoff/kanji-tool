# 同形异音句（历史机制：现由双引擎共识裁决主读音，
# 仅当两引擎真正分歧时才警示——见上方 GOLDEN 中对 行った 两种语境的主读音断言）
AMBIGUOUS = []


def get_reading(tokens, seg):
    """在结果里找表面形等于 seg 的连续 token，拼出读音"""
    # 单 token 精确匹配
    for t in tokens:
        if t['s'] == seg and t['r']:
            return t['r']
    # 多 token 拼接
    for a in range(len(tokens)):
        acc_s, acc_r = '', ''
        for b in range(a, len(tokens)):
            acc_s += tokens[b]['s']
            acc_r += tokens[b]['r'] or ''
            if acc_s == seg:
                return acc_r
            if len(acc_s) > len(seg):
                break
    return None


def test_dict_form():
    """词组索引必须用词典原形，不能是活用残段（貧しかっ→貧しい）"""
    fails = 0
    cases = [('生活が貧しかった。', '貧', '貧しい', 'まずしい'),
             ('本を読んだ。', '読', '読む', 'よむ'),
             ('嬉しくて泣いた。', '嬉', '嬉しい', 'うれしい')]
    for sent, kanji, want_w, want_r in cases:
        kw = furigana.extract_kanji_words(furigana.annotate(sent))
        hit = [(w, r) for k, w, r in kw if k == kanji]
        if (want_w, want_r) not in hit:
            print(f'✗ 词组原形: {sent} 「{kanji}」期望 {want_w}({want_r}) 实得 {hit}')
            fails += 1
    return fails


def main():
    passed = failed = 0
    for sent, expects in GOLDEN:
        tokens = furigana.annotate(sent)
        for seg, want in expects.items():
            got = get_reading(tokens, seg)
            wants = want.split(',')
            if got in wants:
                passed += 1
            else:
                failed += 1
                print(f'✗ {sent}  「{seg}」期望 {want} 实得 {got}')
                print('   ', ' '.join(f"{t['s']}({t['r']})" if t['r'] else t['s'] for t in tokens))
    for sent, seg in AMBIGUOUS:
        tokens = furigana.annotate(sent)
        tok = next((t for t in tokens if seg.startswith(t['s']) or t['s'].startswith(seg[0])), None)
        flagged = any(t.get('alt') or t.get('c') == 'low' for t in tokens if t.get('w') and seg in t['w'])
        if flagged:
            passed += 1
            alts = [t.get('alt') for t in tokens if t.get('alt')]
            print(f'⚠ 歧义正确检出: {sent} 「{seg}」候选 {alts}')
        else:
            failed += 1
            print(f'✗ 歧义未检出: {sent} 「{seg}」')
    failed += test_dict_form()
    passed += 3 - min(3, failed)
    print(f'\n===== 通过 {passed} / {passed + failed} =====')
    return failed


