def full_reading(word):
    toks = furigana.annotate(word)
    return ''.join(t.get('r') or t['s'] for t in toks)


def main():
    ok = fail = 0
    for word, accepts in TESTS:
        got = full_reading(word)
        if got in accepts:
            ok += 1
            print('OK   %-8s %s' % (word, got))
        else:
            fail += 1
            print('FAIL %-8s 期望 %s 实得 %s' % (word, '/'.join(accepts), got))
    print('\n==== 通过 %d / %d ====' % (ok, ok + fail))
    if fail:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
