def _norm(v):
    return v if isinstance(v, (set, frozenset, tuple, list)) else (v,)


def _match_pred(w, pred):
    f = w.feature
    if 's' in pred and w.surface not in _norm(pred['s']):
        return False
    if 'l' in pred and (f.lemma or '') not in _norm(pred['l']):
        return False
    if 'p1' in pred and f.pos1 not in _norm(pred['p1']):
        return False
    if 'p2' in pred and f.pos2 not in _norm(pred['p2']):
        return False
    if 'cf' in pred and not any((f.cForm or '').startswith(x) for x in _norm(pred['cf'])):
        return False
    if 'ct' in pred and not any((f.cType or '').startswith(x) for x in _norm(pred['ct'])):
        return False
    return True


