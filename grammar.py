_TPLS = [
    '「{surface}」是{level}句型「{name}」（接续：{structure}）——{meaning}。在本句「{ctx}」中就是这个用法。',
    '这里的「{surface}」用到了「{name}」：{meaning}。它的接续方式是 {structure}，请对照句中「{ctx}」体会。',
    '注意「{ctx}」这一段：核心语法是「{name}」（{level}）。{meaning}，形态上表现为 {structure}。',
    '「{name}」登场了：{meaning}。本句里它以「{surface}」的形式出现，前后文是「{ctx}」。',
    '拆解「{ctx}」：这是{level}必考的「{name}」，结构为 {structure}。含义：{meaning}。',
    '本句的「{surface}」即「{name}」用法（{structure}）。一句话概括：{meaning}。',
]

_TPLS_SINGLE = [
    '「{surface}」：{name}，{meaning}。',
    '句中「{surface}」是{name}——{meaning}。',
    '这里的「{surface}」（{name}）：{meaning}。',
    '{name}「{surface}」：{meaning}。',
]


def _pick(templates, seed):
    return templates[int(hashlib.md5(seed.encode()).hexdigest(), 16) % len(templates)]


_STOP_PUNCT = {'。', '！', '？', '!', '?', '．'}


def _context3(words, s, e, lr=4, rr=3):
    """三段式上下文：核心语法点前后各取若干形态素、不跨句 → (before, core, after)"""
    lo = max(0, s - lr)
    for j in range(s - 1, lo - 1, -1):
        if words[j].surface in _STOP_PUNCT:
            lo = j + 1
            break
    hi = min(len(words), e + rr)
    for j in range(e, hi):
        if words[j].surface in _STOP_PUNCT:
            hi = j
            break
    before = ''.join(w.surface for w in words[lo:s])
    core = ''.join(w.surface for w in words[s:e])
    after = ''.join(w.surface for w in words[e:hi])
    return before, core, after


def _context(words, s, e, radius=2):
    b, c_, a = _context3(words, s, e, radius, radius)
    return b + c_ + a


def analyze(text: str):
    """返回按 N5→N1 排序的语法点列表"""
    words = [w for w in _tagger(text) if w.surface]
    found = []
    covered = set()

    # ---- 第一级：结构句型匹配 ----
    for pat in PATTERNS:
        seq = pat['seq']
        for start in range(len(words)):
            wi, si, matched = start, 0, []
            while si < len(seq) and wi < len(words):
                pred = seq[si]
                if _match_pred(words[wi], pred):
                    matched.append(wi)
                    wi += 1
                    si += 1
                elif pred.get('opt'):
                    si += 1
                else:
                    break
            while si < len(seq) and seq[si].get('opt'):
                si += 1
            if si < len(seq) or not matched:
                continue
            if pat.get('not_prev_ct') and start > 0:
                pct = words[start - 1].feature.cType or ''
                if any(pct.startswith(x) for x in pat['not_prev_ct']):
                    continue
            if pat.get('not_next_p1') and wi < len(words):
                if words[wi].feature.pos1 in pat['not_next_p1']:
                    continue
            # next_any: 匹配终点后一词必须满足任一谓词（用于强制「な+名词」等搭配）
            if pat.get('next_any') is not None:
                if wi >= len(words) or not any(_match_pred(words[wi], np) for np in pat['next_any']):
                    continue
            if pat['prev_cf'] is not None:
                if start == 0:
                    continue
                pf = words[start - 1].feature.cForm or ''
                if not any(pf.startswith(x) for x in pat['prev_cf']):
                    continue
            s_idx, e_idx = matched[0], matched[-1] + 1
            surface = ''.join(words[j].surface for j in range(s_idx, e_idx))
            ctx = _context(words, s_idx, e_idx)
            seed = f'{text}|{pat["name"]}|{s_idx}'
            explain = _pick(_TPLS, seed).format(
                surface=surface, name=pat['name'], level=pat['level'],
                structure=pat['structure'], meaning=pat['meaning'], ctx=ctx)
            if pat.get('note'):
                explain += ' ' + pat['note']
            b3, c3, a3 = _context3(words, s_idx, e_idx)
            found.append({'name': pat['name'], 'level': pat['level'],
                          'structure': pat['structure'], 'surface': surface,
                          'before': b3, 'core': c3, 'after': a3,
                          'span': [s_idx, e_idx], 'explain': explain, 'kind': 'pattern'})
            covered.update(range(s_idx, e_idx))

    # 同名同span去重
    seen, uniq = set(), []
    for f in found:
        key = (f['name'], f['span'][0], f['span'][1])
        if key not in seen:
            seen.add(key)
            uniq.append(f)
    found = uniq

    # 包含去重：短句型完全被更长句型覆盖时，长句型优先（ざる ⊂ ざるを得ない）
    drop = set()
    for a in range(len(found)):
        for b in range(len(found)):
            if a == b:
                continue
            sa, ea = found[a]['span']
            sb, eb = found[b]['span']
            if sb <= sa and ea <= eb and (eb - sb) > (ea - sa):
                drop.add(a)
    found = [f for j, f in enumerate(found) if j not in drop]

    # ---- 第二级+第三级：功能词兜底，保证零遗漏 ----
    for i, w in enumerate(words):
        if i in covered:
            continue
        f = w.feature
        entry = None
        if f.pos1 == '助詞':
            key = w.surface if not (w.surface == 'が' and f.pos2 == '接続助詞') else 'が(接続)'
            info = PARTICLES.get(key) or PARTICLES.get(f.lemma or '')
            if info:
                entry = info
            else:
                entry = ('N3', f'{f.pos2}「{w.surface}」', '功能助词（本词暂未收录详解，已确保不遗漏）')
        elif f.pos1 == '助動詞':
            info = AUXILIARIES.get(f.lemma or '') or AUXILIARIES.get(w.surface)
            # 「だ」活用形未被句型覆盖的残留：按句中实际功能解释，绝不硬套「断定」
            if (f.lemma or '') == 'だ':
                if w.surface == 'な':
                    info = ('N5', 'な（ナ形容詞の連体形）', 'ナ形容詞＋な「～的」：修饰后续词语（ような美しい表現＝诗一般的美丽表达）')
                elif w.surface == 'で':
                    nxt = words[i + 1] if i + 1 < len(words) else None
                    if nxt is not None and nxt.surface == 'も':
                        info = ('N4', 'で＋も（でも）', '断定连用形で＋も「即使～也」：おじいさんでもおかしくない＝就算是老爷爷也不奇怪')
                    else:
                        info = ('N5', 'で（だの連用形）', '这里实质等同格助詞で：手段/场所/范围（ことで＝通过～的方式）')
            if info:
                entry = info
            else:
                entry = ('N3', f'助動詞「{w.surface}」', f'助动词（原形：{f.lemma}），已标记待补充详解')
        if entry:
            level, name, meaning = entry
            seed = f'{text}|{name}|{i}'
            explain = _pick(_TPLS_SINGLE, seed).format(
                surface=w.surface, name=name, meaning=meaning)
            b3, c3, a3 = _context3(words, i, i + 1)
            found.append({'name': name, 'level': level, 'structure': '—',
                          'surface': w.surface, 'before': b3, 'core': c3, 'after': a3,
                          'span': [i, i + 1], 'explain': explain, 'kind': 'word'})

    # ---- 同名语法点合并：句中多次出现 → 一条条目 + 全部上下文 ----
    merged, order = {}, []
    for f in found:
        key = (f['name'], f['level'])
        occ = {'surface': f['surface'], 'before': f['before'],
               'core': f['core'], 'after': f['after']}
        if key in merged:
            merged[key]['occurrences'].append(occ)
            merged[key]['count'] += 1
        else:
            f = dict(f)
            f['occurrences'] = [occ]
            f['count'] = 1
            merged[key] = f
            order.append(key)
    found = [merged[k] for k in order]

    # ---- 排序：由浅入深（N5→N1），同级按句中位置 ----
    found.sort(key=lambda x: (LEVEL_ORDER.get(x['level'], 9), x['span'][0]))
    return found


