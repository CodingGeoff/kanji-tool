# 无把握时必须保留大纲通用名（诚实兜底，不得乱猜）
FALLBACK_CASES = [
    # つつある 结构：通用名即精准（不进入つつ二分）
    ('人口が減りつつある。', '〜つつある（進行）'),
]


def main():
    passed, failed = 0, []
    for text, anchor, expect in CASES:
        try:
            pts = [p for p in grammar.analyze(text)
                   if p.get('kind') == 'pattern'
                   and (anchor in (p.get('surface') or '') or anchor in p.get('name', ''))]
        except Exception as e:  # pragma: no cover
            failed.append((text, expect, f'analyze异常: {e}'))
            continue
        names = [p['name'] for p in pts]
        hit = next((p for p in pts if p['name'] == expect), None)
        if hit is None:
            failed.append((text, expect, f'未命中，实际: {names}'))
            continue
        if '（判据：' not in hit.get('explain', ''):
            failed.append((text, expect, '命中但讲解缺少判据'))
            continue
        passed += 1
    for text, expect in FALLBACK_CASES:
        try:
            names = [p['name'] for p in grammar.analyze(text) if p.get('kind') == 'pattern']
        except Exception as e:  # pragma: no cover
            failed.append((text, expect, f'analyze异常: {e}'))
            continue
        if expect in names:
            passed += 1
        else:
            failed.append((text, expect, f'兜底丢失，实际: {names}'))
    print(f'===== 消歧专项: 通过 {passed} / {passed + len(failed)} =====')
    for text, expect, reason in failed:
        print(f'FAIL: {text}\n  期望: {expect}\n  原因: {reason}')
    return 0 if not failed else 1


if __name__ == '__main__':
    sys.exit(main())
