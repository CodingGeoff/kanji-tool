for word, exp in TESTS:
    got = full_reading(word)
    if got == exp:
        ok += 1
        print('OK   %-6s %s' % (word, got))
    else:
        fail += 1
        print('FAIL %-6s 期望=%s 实得=%s   [%s]' % (word, exp, got, show(word)))

print('\n==== 通过 %d / %d ====' % (ok, ok + fail))
