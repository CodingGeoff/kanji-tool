def full_reading(word):
    toks = furigana.annotate(word)
    out = ''
    for t in toks:
        out += (t.get('r') or t['s'])
    return out


def show(word):
    toks = furigana.annotate(word)
    return ' '.join('%s=%s' % (t['s'], t.get('r') or '-') for t in toks)


