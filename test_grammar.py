def run():
    import re as _re
    n_pass, fails = 0, []
    dup_re = _re.compile(r'「([^」]{1,10})」[^「」]{0,8}「\1」')
    for text, expects, rejects in CASES:
        points = grammar.analyze(text)
        names = [p['name'] for p in points]
        ok = True
        # 全局断言：解释引用必须可独立阅读，不重复引用、不以标点起止。
        for p in points:
            if dup_re.search(p['explain']):
                fails.append(f'重复引用: {text}  「{p["explain"][:40]}」')
                ok = False
            for occ in p.get('occurrences') or []:
                frag = (occ.get('before') or '') + (occ.get('core') or '') + (occ.get('after') or '')
                if not frag:
                    continue
                if frag[0] in grammar._PHRASE_EDGE_PUNCT or frag[-1] in grammar._PHRASE_EDGE_PUNCT:
                    fails.append(f'引用片段以标点起止: {text} →「{frag}」')
                    ok = False

        for exp in expects:
            if not any(exp in n for n in names):
                fails.append(f'漏报: {text}  期望「{exp}」 实际: {names}')
                ok = False
        for rname, rsurf in rejects:
            for p in points:
                if rname in p['name'] and any(o['core'] == rsurf for o in p['occurrences']):
                    fails.append(f'误报: {text}  不应有「{rname}」@「{rsurf}」')
                    ok = False
        if ok:
            n_pass += 1

    # 边界专项：引号后的引用助词不得成为片段开头；活用词不得在「読んでい」
    # 之类的半截处结束。这里直接检查原句形态素窗口，避免把短片段重新分词时
    # 因歧义产生与原句不同的词性。
    if not any('请结合句中「{ctx}」体会。' in tpl
               for tpl in grammar._TPLS + grammar._TPLS_NOSURF):
        fails.append('语法讲解模板应使用简洁措辞“请结合句中「……」体会。”')
    if any('相对完整的片段' in tpl for tpl in grammar._TPLS + grammar._TPLS_NOSURF):
        fails.append('语法讲解模板不应声称上下文一定是完整句子')

    boundary_samples = [
        ('彼は「行こう」と言った。', '助動詞「た」', '言った'),
        ('彼は毎日図書館で本を読んでいます。', '〜ます（丁寧体）', '読んでいます'),
        ('このように、色は生活に役立っているのです。', '〜ている', '生活に役立っている'),
    ]
    for text, name_part, required in boundary_samples:
        matches = [p for p in grammar.analyze(text) if name_part in p['name']]
        fragments = [(o['before'] + o['core'] + o['after'])
                     for p in matches for o in p.get('occurrences', [])]
        if not fragments or not any(required in frag for frag in fragments):
            fails.append(f'引用片段不完整: {text} 期望包含「{required}」 实际 {fragments}')

    print(f'===== 语法金标准: 通过 {n_pass} / {len(CASES)} =====')
    for f in fails:
        print(' ', f)
    return len(fails)


if __name__ == '__main__':
    sys.exit(0 if run() == 0 else 1)
